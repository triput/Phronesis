def resolve_icon_name(raw: str | None) -> str:
    """Return a canonical Heroicons outline name, falling back to ``folder``."""
    if not raw:
        return DEFAULT_ICON
    key = str(raw).strip().lower().replace("_", "-")
    key = ICON_ALIASES.get(key, key)
    if key in HEROICON_PATHS:
        return key
    return DEFAULT_ICON


def icon_path_data(name: str | None) -> tuple[str, str]:
    """Resolve *name* and return ``(canonical_name, svg_path_d)``."""
    canonical = resolve_icon_name(name)
    return canonical, HEROICON_PATHS[canonical]
